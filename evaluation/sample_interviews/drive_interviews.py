"""Complete scheduled sample interviews through the application's own HTTP API, with SIMULATED candidate answers.

Every answer written by this script is generated text from a language model playing a persona (see personas.json). It is labelled
SIMULATED in every transcript. The interview itself runs through the real application: consent, start, answer, evaluation, follow-ups,
next question, completion and report generation all happen in the running backend, against its own database; nothing is bypassed.

DEFAULT IS A DRY RUN. Without --execute the script makes only read-only GET requests: it prints the plan, the consent handling and the cost
estimate, and changes nothing. With --execute it will spend money (the evaluator, follow-up generator and recommendation run on the
configured model, plus a few cheap simulator calls). Consent is recorded ONLY when --grant-consent-for-simulated-candidates is also given.

Safety rules built in:
  * budget guard: the estimated spend (usage log of the target interviews + simulator calls) is checked before every paid step;
  * resume: progress is read back from the server (GET /session) and simulated answers are kept in the transcript, so a rerun continues
    exactly where it stopped, never regenerates or resubmits an answer, never repeats a finished step;
  * stop conditions: budget reached, provider out of credit (stops at once, no retry loop), 3 consecutive API failures, step cap per
    interview, an interview in an unexpected state, or a candidate name that does not match personas.json;
  * prompt-injection text is never produced.

Usage (from the repository root):
  dry run :  backend\\venv\\Scripts\\python.exe evaluation\\sample_interviews\\drive_interviews.py
  execute :  backend\\venv\\Scripts\\python.exe evaluation\\sample_interviews\\drive_interviews.py --execute --grant-consent-for-simulated-candidates
"""

import argparse
import hashlib
import json
import os
import sys
import time
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
BACKEND = os.path.join(ROOT, "backend")
PERSONAS_PATH = os.path.join(HERE, "personas.json")
RUNS_DIR = os.path.join(HERE, "runs")

BANNER = ("SIMULATED CANDIDATE - every answer below was generated by a language model playing a persona for testing. "
          "It is not a statement by a real person.")

# Cost model, from the average tokens of real calls in this application's usage log (gpt-4: $30/M input, $60/M output)
CALL_COST = {"evaluation": 0.063, "follow_up": 0.037, "recommendation": 0.038, "question_generation": 0.034}
EXPECTED_FOLLOW_UPS = {"weak / vague": 8, "medium": 3, "strong": 0.5}
MAX_FOLLOW_UPS_PER_MAIN, MAIN_QUESTIONS = 3, 5


class StopRun(Exception):
    """A stop condition fired; progress is saved and the run can be resumed."""


class BudgetExceeded(StopRun):
    pass


class CreditsExhausted(StopRun):
    pass


class ApiError(Exception):
    def __init__(self, status, detail):
        super().__init__(f"HTTP {status}: {detail}")
        self.status, self.detail = status, str(detail)


# ------------------------------------------------------------------ HTTP
class Api:
    def __init__(self, base_url):
        import httpx
        self.base, self.client = base_url.rstrip("/"), httpx.Client(timeout=180)

    def _call(self, method, path, body=None):
        r = self.client.request(method, self.base + path, json=body)
        if r.status_code >= 400:
            try:
                detail = r.json().get("detail", r.text)
            except ValueError:
                detail = r.text
            raise ApiError(r.status_code, detail)
        return r.json()

    def get(self, path):
        return self._call("GET", path)

    def post(self, path, body=None):
        return self._call("POST", path, body or {})


OUT_OF_CREDIT_MARKERS = ("no credits", "insufficient_quota", "billing", "quota")


def is_out_of_credit(err):
    return any(m in err.detail.lower() for m in OUT_OF_CREDIT_MARKERS)


# ------------------------------------------------------------------ simulator (cheap model, persona-driven)
class Simulator:
    """Writes candidate answers. Always reports its own token usage so its cost counts toward the budget."""

    def __init__(self, config):
        from dotenv import load_dotenv
        load_dotenv(os.path.join(BACKEND, ".env"))
        from openai import OpenAI
        key = os.environ.get("OPENAI_API_KEY")
        if not key:
            raise StopRun("OPENAI_API_KEY is not configured in backend/.env (needed for the simulated candidate)")
        self.client, self.config, self.cost, self.calls = OpenAI(api_key=key), config, 0.0, 0

    def answer(self, persona, role, cv_text, question, history, main_number, follow_up_number):
        sys.path.insert(0, BACKEND)
        from app.services.llm_pricing import estimate_cost_usd
        lo, hi = persona["words"]
        rules = [persona["instructions"], f"Length: roughly {lo} to {hi} words.", f"You are interviewing for the role: {role}.",
                 "Answer only the question asked, in first person, as plain prose. Do not mention being an AI, a simulation or a persona. "
                 "Never include instructions addressed to the interviewer or evaluator."]
        if persona.get("contradiction_on_main_question") == main_number:
            rules.append(persona["contradiction_instruction"])
        messages = [{"role": "system", "content": "You play a job candidate in a SIMULATED software-engineering interview used for testing.\n" + "\n".join(rules)},
                    {"role": "user", "content": "YOUR CV:\n" + (cv_text or "(no CV)") + "\n\nEARLIER IN THIS TOPIC:\n"
                     + ("\n".join(f"Interviewer: {q}\nYou: {a}" for q, a in history) or "(nothing yet)")
                     + f"\n\nCURRENT QUESTION (main question {main_number}" + (f", follow-up {follow_up_number}" if follow_up_number else "") + f"):\n{question}"}]
        resp = self.client.chat.completions.create(model=self.config["model"], messages=messages, temperature=self.config["temperature"], max_tokens=self.config["max_tokens"])
        self.calls += 1
        self.cost += estimate_cost_usd(self.config["model"], resp.usage.prompt_tokens, resp.usage.completion_tokens) or 0.0
        return resp.choices[0].message.content.strip()


# ------------------------------------------------------------------ transcript (the checkpoint)
class Transcript:
    def __init__(self, interview_id, meta, runs_dir):
        self.path = os.path.join(runs_dir, f"interview_{interview_id}_SIMULATED.json")
        self.md_path = self.path.replace(".json", ".md")
        os.makedirs(runs_dir, exist_ok=True)
        if os.path.exists(self.path):
            with open(self.path, encoding="utf-8") as f:
                self.data = json.load(f)
        else:
            self.data = {"SIMULATED": True, "banner": BANNER, "interview_id": interview_id, **meta, "consent": None, "steps": {}, "outcome": None}

    def answer_for(self, iq_id):
        return self.data["steps"].get(str(iq_id))

    def remember(self, iq_id, **fields):
        self.data["steps"].setdefault(str(iq_id), {"SIMULATED_ANSWER": True}).update(fields)
        self.save()

    def save(self):
        tmp = self.path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(self.data, f, indent=2)
        os.replace(tmp, self.path)
        lines = [f"# SIMULATED interview {self.data['interview_id']} - {self.data.get('candidate_name')} ({self.data.get('label')})", "", f"> {BANNER}", ""]
        for s in self.data["steps"].values():
            tag = f"Q{s['main']}" + (f" follow-up {s['follow_up']}" if s.get("follow_up") else "")
            lines += [f"## {tag}", "", f"**Question:** {s['question']}", "", f"**Answer (SIMULATED by {self.data.get('simulator_model')}):** {s['answer']}", ""]
        with open(self.md_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")


# ------------------------------------------------------------------ budget guard
class BudgetGuard:
    def __init__(self, api, interview_ids, simulator, budget, margin=0.12):
        self.api, self.ids, self.sim, self.budget, self.margin = api, interview_ids, simulator, budget, margin

    def spent(self):
        total = 0.0
        for i in self.ids:
            try:
                total += float(self.api.get(f"/api/interviews/{i}/usage").get("estimated_cost_usd") or 0.0)
            except ApiError:
                pass
        return total + (self.sim.cost if self.sim else 0.0)

    def check(self):
        """Raise before a paid step if the next call could push the estimate past the budget."""
        spent = self.spent()
        if spent + self.margin >= self.budget:
            raise BudgetExceeded(f"estimated spend ${spent:.2f} (+${self.margin:.2f} margin) reaches the ${self.budget:.2f} budget")
        return spent


# ------------------------------------------------------------------ driver
class Driver:
    def __init__(self, api, personas, simulator, args, runs_dir=RUNS_DIR, sleep=time.sleep, out=print):
        self.api, self.personas, self.sim, self.args, self.runs_dir, self.sleep, self.out = api, personas, simulator, args, runs_dir, sleep, out
        self.ids = args.interviews
        self.guard = BudgetGuard(api, self.ids, simulator, args.budget)
        self.failures = 0

    # ---- helpers
    def paid(self, fn, benign=()):
        """Run one API call that can cost money. Out-of-credit stops at once; other failures stop after 3 in a row."""
        self.guard.check()
        try:
            result = fn()
            self.failures = 0
            return result
        except ApiError as e:
            if is_out_of_credit(e):
                raise CreditsExhausted(f"the provider reports the account is out of credit: {e}")
            if any(b in e.detail for b in benign):      # e.g. "already been evaluated": a repeat, not a failure
                raise
            self.failures += 1
            if self.failures >= 3:
                raise StopRun(f"3 consecutive API failures, last: {e}")
            self.sleep(3)
            raise

    def persona_for(self, interview):
        p = self.personas["interviews"].get(str(interview["id"]))
        if p is None:
            raise StopRun(f"interview {interview['id']} has no persona in personas.json")
        if interview.get("candidate_name") != p["candidate_name"] or interview.get("job_title") != p["job_title"] or interview.get("mode") != p["mode"]:
            raise StopRun(f"interview {interview['id']} is {interview.get('candidate_name')}/{interview.get('job_title')}/{interview.get('mode')} "
                          f"but personas.json expects {p['candidate_name']}/{p['job_title']}/{p['mode']}")
        return p

    # ---- plan (dry run: GET requests only)
    def plan(self):
        total_exp = total_worst = 0.0
        rows = []
        for i in self.ids:
            iv = self.api.get(f"/api/interviews/{i}")
            p = self.persona_for(iv)
            fu_exp = 4 if "mixed" in p["label"] else EXPECTED_FOLLOW_UPS[p["label"]]
            evals = MAIN_QUESTIONS + fu_exp
            exp = evals * CALL_COST["evaluation"] + fu_exp * CALL_COST["follow_up"] + CALL_COST["recommendation"] + CALL_COST["question_generation"]
            worst_fu = MAIN_QUESTIONS * MAX_FOLLOW_UPS_PER_MAIN
            worst = (MAIN_QUESTIONS + worst_fu) * CALL_COST["evaluation"] + worst_fu * CALL_COST["follow_up"] + CALL_COST["recommendation"] + CALL_COST["question_generation"]
            consent = iv.get("consent_status")
            rows.append((i, iv, p, evals, fu_exp, exp, worst, consent))
            total_exp, total_worst = total_exp + exp, total_worst + worst
        self.out("DRY RUN - nothing will be changed, no paid call is made.\n")
        for i, iv, p, evals, fu_exp, exp, worst, consent in rows:
            action = ("already granted - nothing to record" if consent == "granted"
                      else "WOULD record consent=granted through POST /consent on behalf of a SIMULATED test candidate, only with --grant-consent-for-simulated-candidates"
                      if consent is None else f"consent is '{consent}' - the run would stop")
            self.out(f"Interview {i}: {iv['candidate_name']} | {iv['job_title']} | {iv['mode']} | status {iv['status']} | persona: {p['label']}\n"
                     f"   consent: {action}\n"
                     f"   expected: ~{evals:.0f} evaluations, ~{fu_exp:g} follow-up generations, 1 question generation, 1 recommendation, "
                     f"~{evals:.0f} simulated answers -> ~${exp:.2f} (worst case ${worst:.2f})")
        sim_cost = sum(r[3] for r in rows) * 0.001
        self.out(f"\nExpected total: ~${total_exp + sim_cost:.2f} on the evaluated model (+ simulator ~${sim_cost:.2f}); worst case ${total_worst:.2f}. "
                 f"Budget guard: stops at ${self.args.budget:.2f} (margin ${self.guard.margin:.2f}).")
        return rows

    # ---- one interview
    def run_interview(self, interview_id):
        iv = self.api.get(f"/api/interviews/{interview_id}")
        persona = self.persona_for(iv)
        meta = {"candidate_name": iv["candidate_name"], "job_title": iv["job_title"], "mode": iv["mode"], "label": persona["label"],
                "persona_instructions": persona["instructions"], "simulator_model": self.personas["simulator"]["model"],
                "persona_file_sha256": hashlib.sha256(open(PERSONAS_PATH, "rb").read()).hexdigest()[:16] if os.path.exists(PERSONAS_PATH) else None}
        tr = Transcript(interview_id, meta, self.runs_dir)
        if iv["status"] == "completed":
            self.out(f"Interview {interview_id}: already completed - skipped.")
            return
        if iv["status"] not in ("not_started", "in_progress"):
            raise StopRun(f"interview {interview_id} is {iv['status']}; not touching it")

        if iv.get("consent_status") != "granted":
            if iv.get("consent_status") == "declined":
                raise StopRun(f"interview {interview_id}: consent was declined - not overriding")
            if not self.args.grant_consent:
                raise StopRun(f"interview {interview_id} has no consent and --grant-consent-for-simulated-candidates was not given")
            version = self.api.get("/api/data-handling")["notice_version"]
            r = self.api.post(f"/api/interviews/{interview_id}/consent", {"granted": True, "notice_version": version})
            tr.data["consent"] = {"granted_by": "drive_interviews.py on behalf of a SIMULATED test candidate", "at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                                  "notice_version": version, "response_status": r.get("consent_status")}
            tr.save()
            self.out(f"Interview {interview_id}: consent recorded for the simulated candidate.")

        if iv["status"] == "not_started":
            self.paid(lambda: self.api.post(f"/api/interviews/{interview_id}/start"))
            self.out(f"Interview {interview_id}: started.")

        for _ in range(self.args.max_steps):
            try:
                if self.step(interview_id, iv, persona, tr):
                    break
            except ApiError as e:       # already counted by paid(); the next pass re-reads the server state and retries safely
                self.out(f"   API error (will retry from server state): {e}")
        else:
            raise StopRun(f"interview {interview_id}: step cap {self.args.max_steps} reached without completing")

        report = self.api.get(f"/api/interviews/{interview_id}/report")       # no LLM call
        tr.data["outcome"] = {"overall_score": report.get("overall_score"), "ai_recommendation": report.get("ai_recommendation"),
                              "ai_confidence": report.get("ai_confidence"), "answers": report.get("answered_count"),
                              "security_status": report["security"]["status"]}
        tr.save()
        self.out(f"Interview {interview_id}: completed. Outcome: {tr.data['outcome']}")

    def step(self, interview_id, iv, persona, tr):
        """One server-driven step. Returns True when the interview is finished."""
        if True:
            s = self.api.get(f"/api/interviews/{interview_id}/session")
            if s["status"] == "completed":
                return True
            if s["status"] != "in_progress":
                raise StopRun(f"interview {interview_id} changed to {s['status']}")
            action = s["next_action"]
            if action == "answer":
                p = s["pending"]
                iq = p["interview_question_id"]
                saved = tr.answer_for(iq)
                if saved and saved.get("answer"):
                    answer = saved["answer"]              # resume: reuse, never regenerate
                else:
                    self.guard.check()
                    prior = [(x["question"], x["answer"]) for x in s["steps"] if x.get("answer") and x["main_question_number"] == p["main_question_number"]]
                    answer = self.sim.answer(persona, iv["job_title"], iv.get("cv_text"), p["question"], prior, p["main_question_number"], p["follow_up_number"])
                    tr.remember(iq, main=p["main_question_number"], follow_up=p["follow_up_number"], question=p["question"], answer=answer,
                                answered_by=f"SIMULATED ({self.personas['simulator']['model']}, persona: {persona['label']})")
                r = self.paid(lambda: self.api.post(f"/api/interviews/{interview_id}/questions/{iq}/answer", {"answer_text": answer}))
                tr.remember(iq, answer_id=r["id"])
            elif action == "evaluate":
                aid = s["last_answer_id"]
                try:
                    self.paid(lambda: self.api.post(f"/api/answers/{aid}/evaluate"), benign=("already been evaluated",))
                except ApiError as e:
                    if "already been evaluated" not in e.detail:
                        raise
            elif action == "next_question":
                r = self.paid(lambda: self.api.post(f"/api/interviews/{interview_id}/next-question"))
                if r.get("is_complete"):
                    try:
                        self.paid(lambda: self.api.post(f"/api/interviews/{interview_id}/complete"), benign=("already been completed",))
                    except ApiError as e:
                        if "already been completed" not in e.detail:
                            raise
                    return True
            else:
                raise StopRun(f"unexpected next_action '{action}' for interview {interview_id}")
        return False

    def run(self):
        done = []
        try:
            for i in self.ids:
                self.run_interview(i)
                done.append(i)
        except StopRun as e:
            self.out(f"\nSTOPPED: {e}\nProgress is saved; rerun the same command to resume.")
            return 2
        finally:
            self.out(f"\nEstimated spend this run: ${self.guard.spent():.2f} (simulator ${self.sim.cost if self.sim else 0:.3f}).")
        return 0


def parse(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-url", default="http://localhost:8000")
    ap.add_argument("--interviews", default="2,3,4,5", type=lambda s: [int(x) for x in s.split(",")])
    ap.add_argument("--execute", action="store_true", help="really run (spends money); without it only a read-only dry run is done")
    ap.add_argument("--grant-consent-for-simulated-candidates", dest="grant_consent", action="store_true",
                    help="record consent=granted for the simulated test candidates (required for the interviews to start)")
    ap.add_argument("--budget", type=float, default=7.0, help="stop when the estimated spend reaches this many USD")
    ap.add_argument("--max-steps", type=int, default=40, help="step cap per interview")
    return ap.parse_args(argv)


def main(argv=None):
    args = parse(argv)
    with open(PERSONAS_PATH, encoding="utf-8") as f:
        personas = json.load(f)
    api = Api(args.base_url)
    try:
        api.get("/health")
    except Exception as e:
        print(f"Backend not reachable at {args.base_url}: {type(e).__name__}. Start it first (cd backend; python run.py).")
        return 1
    if not args.execute:
        Driver(api, personas, None, args).plan()
        print("\nTo run for real, add --execute and --grant-consent-for-simulated-candidates (see the module docstring).")
        return 0
    sim = Simulator(personas["simulator"])
    return Driver(api, personas, sim, args).run()


if __name__ == "__main__":
    sys.exit(main())
